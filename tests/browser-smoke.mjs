import assert from 'node:assert/strict';
const { default: playwright } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright');
const launch = { headless: true };
if (process.env.CHROMIUM_MODULE) {
  const { default: chromium } = await import(process.env.CHROMIUM_MODULE);
  Object.assign(launch, { executablePath: await chromium.executablePath(), args: chromium.args });
}
const browser = await playwright.chromium.launch(launch);
const errors = [];
const url = process.env.TEST_URL || 'http://127.0.0.1:4173';
const out = process.env.SCREENSHOT_DIR || '/tmp';
try {
  const page = await browser.newPage({viewport:{width:1440,height:900}});
  page.on('pageerror', error => errors.push(error.message));
  page.on('console', message => { if (message.type()==='error' && !message.text().includes('Failed to load resource')) errors.push(message.text()); });
  page.on('dialog', dialog => dialog.accept());
  await page.goto(url);
  await page.locator('.vacancy-card').first().waitFor();
  await page.evaluate(async () => { window.testState = (await import('./js/state.js')).appState; });
  const snapshot = () => page.evaluate(() => ({ count:testState.candidates.length, job:testState.activeJobPostingId, view:testState.currentView, selected:testState.selectedCandidateId, pool:testState.comparisonPool.size }));
  await page.locator('[data-nav="comparison"]').click();
  assert.equal((await snapshot()).pool,0);
  await page.locator('[data-compare-action="suggest"]').click();
  assert.equal((await snapshot()).pool,3);
  await page.locator('[data-compare-action="clear"]').click();
  assert.equal((await snapshot()).pool,0);
  await page.locator('[data-nav="ranking"]').click();
  const originalRoute = page.url();
  await page.locator('#openIngestionBtn').click();
  await page.locator('#demoBatchSize').selectOption('500');
  await page.locator('[data-batch="start"]').click();
  await page.waitForFunction(() => testState.candidates.length===505);
  await page.locator('[data-batch="close"]').click();
  assert.equal(await page.locator('#navCandidateCountBadge').textContent(),'505 demo');
  assert.ok(await page.locator('.candidate-row').count()<25);
  const row = page.locator('.candidate-row').first();
  assert.ok(Math.abs((await row.boundingBox()).height-52)<2);
  const id = await row.getAttribute('data-id');
  await row.locator('.candidate-name').click();
  await page.locator('#drawerBackdrop.active').waitFor();
  await page.locator('#drawerTab_cv').click();
  assert.ok(page.url().includes('tab=cv'));
  await page.locator('#drawerBtnAdvance').click();
  assert.match(await page.locator('#drawerCandidateName').textContent(),/Preseleccionado|evaluación|oferta/i);
  await page.locator('#drawerBtnRelease').click();
  assert.match(await page.locator('#drawerCandidateName').textContent(),/Liberado/);
  await page.locator('#drawerCloseBtn').click();
  await page.locator('[data-nav="kanban"]').click();
  assert.equal(await page.locator('.kanban-column-count').allTextContents().then(a=>a.reduce((sum,n)=>sum+Number(n),0)),505);
  assert.equal(await page.locator('.kanban-column').last().locator('.kanban-column-count').textContent(),'1');
  assert.equal(await page.locator('#globalRoleSelect').count(), 0);
  await page.locator('[data-nav="talentPool"]').click();
  assert.ok(await page.locator('.talent-card').count()>0);
  await page.locator('[data-nav="criteria"]').click();
  const fields=page.locator('[data-weight]');
  for(let i=0;i<await fields.count();i++) await fields.nth(i).fill(i===0?'100':'0');
  await page.locator('[data-criteria-action="save"]').click();
  assert.equal(await page.evaluate(()=>testState.jobPosting.criteriaVersion),'Demo 2');
  await page.locator('[data-nav="ranking"]').click();
  await page.waitForTimeout(500);
  await page.screenshot({path:`${out}/talentai-ranking-desktop.png`});
  await page.reload();
  await page.locator('.candidate-row').first().waitFor();
  await page.evaluate(async()=>{window.testState=(await import('./js/state.js')).appState;});
  assert.equal((await snapshot()).count,505);
  assert.equal(await page.evaluate(id=>testState.candidates.find(c=>c.id===id).stage,id),'liberado');
  await page.locator('#navNewJobBtn').click();
  await page.locator('[data-wizard="next"]').click();
  await page.locator('[name="title"]').fill('Analista demo QA');
  await page.locator('[name="department"]').fill('GTHC');
  await page.locator('[data-wizard="next"]').click();
  await page.locator('[data-wizard="back"]').click();
  assert.equal(await page.locator('[name="title"]').inputValue(),'Analista demo QA');
  await page.locator('[data-wizard="next"]').click();
  await page.locator('[data-wizard="next"]').click();
  await page.locator('[data-wizard="activate"]').click();
  assert.equal((await snapshot()).count,0);
  assert.equal((await snapshot()).view,'ranking');
  await page.locator('[data-nav="comparison"]').click();
  assert.match(await page.locator('#viewContainer_comparison').textContent(),/aún no tiene candidatos/);
  await page.goBack();
  assert.equal((await snapshot()).view,'ranking');
  await page.goBack();
  assert.equal((await snapshot()).count,505);
  assert.match(await page.locator('#userProfileName').textContent(), /Equipo de GTHC/);
  assert.equal(await page.locator('#openIngestionBtn').isDisabled(),false);
  assert.equal(await page.locator('#topNInput').isDisabled(),false);
  await page.locator('[data-nav="executive"]').click();
  assert.match(await page.locator('#viewContainer_executive').textContent(),/510/);
  const mobile = await browser.newPage({viewport:{width:390,height:844},isMobile:true,hasTouch:true});
  mobile.on('pageerror', error => errors.push(error.message));
  await mobile.goto(originalRoute);
  await mobile.locator('.candidate-row').first().waitFor();
  await mobile.waitForTimeout(400);
  assert.equal(await mobile.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1),true);
  await mobile.screenshot({path:`${out}/talentai-ranking-mobile.png`});
  await mobile.locator('.candidate-row .candidate-name').first().click();
  await mobile.locator('#drawerBackdrop.active').waitFor();
  await mobile.waitForTimeout(400);
  const closeBounds = await mobile.locator('#drawerCloseBtn').boundingBox();
  assert.ok(closeBounds.x >= 0 && closeBounds.x + closeBounds.width <= 390);
  assert.equal(await mobile.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1),true);
  await mobile.screenshot({path:`${out}/talentai-drawer-mobile.png`});
  await mobile.locator('#drawerCloseBtn').click();
  assert.deepEqual(errors,[]);
  console.log('Browser flows passed: comparison, 500-profile batch, drawer, stages, bank, weights, reload, wizard, history, roles, panels, mobile.');
} finally { await browser.close(); }
